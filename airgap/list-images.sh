#!/usr/bin/env bash
# Write images.txt: every third-party image the platform needs, fully qualified and
# pinned by digest. Phase 8 mirrors exactly this list.
#
# Images come from the files that pin them, so there is one source of truth per image.
# Fails if any image is not pinned by digest, or (unless --offline) if a pinned digest
# doesn't exist in its registry.
#
# Usage: list-images.sh <helm binary> [--offline]
set -euo pipefail

HELM=${1:?helm binary}
OFFLINE=${2:-}
APP_REPO=secure-k8s-app   # built in this repo, see the note in the header below
OUT=images.txt

# docker.io short names -> fully qualified (registry:3 -> docker.io/library/registry:3).
qualify() {
  local ref=$1 first=${1%%/*}
  if [[ $ref != */* ]]; then
    echo "docker.io/library/$ref"
  elif [[ $first != *.* && $first != *:* && $first != localhost ]]; then
    echo "docker.io/$ref"
  else
    echo "$ref"
  fi
}

# "<source>|<image ref>" lines.
collect() {
  sed -n 's/^ *image: *//p' cluster/kind-config.yaml | sed 's/^/cluster\/kind-config.yaml|/'
  sed -n 's/^REG_IMAGE=//p' cluster/registry.sh | sed 's/^/cluster\/registry.sh|/'
  awk 'toupper($1) == "FROM" {print "app/Dockerfile|" $2}' app/Dockerfile
  "$HELM" template app charts/app -f charts/app/ci/lint-values.yaml \
    | sed -n 's/^ *image: *//p' | tr -d '"' | grep -v "/$APP_REPO:" \
    | sed 's/^/charts\/app (rendered)|/' || true
}

failed=0
entries=$(collect | sort -t'|' -k2 -u)
while IFS='|' read -r src ref; do
  if [[ $ref != *@sha256:* ]]; then
    echo "NOT PINNED  $ref  ($src)" >&2; failed=1; continue
  fi
  if [[ $OFFLINE != --offline ]]; then
    want=${ref##*@}
    got=$(docker buildx imagetools inspect "$ref" --format '{{.Manifest.Digest}}' 2>/dev/null || true)
    if [[ $got != "$want" ]]; then
      echo "DIGEST NOT FOUND  $ref  ($src)" >&2; failed=1; continue
    fi
  fi
done <<<"$entries"
[[ $failed -eq 0 ]] || { echo "images.txt not written" >&2; exit 1; }

{
  echo "# Generated by \`make images\`. Do not edit: change the pin at its source instead."
  echo "# Third-party images, fully qualified, pinned by digest. Phase 8 mirrors exactly this list."
  echo "#"
  echo "# Not listed:"
  echo "#  - $APP_REPO: built and pushed by this repo; its digest changes with every build (ADR 0003)."
  echo "#  - kube-*, etcd, coredns, kindnet, local-path-provisioner: preloaded in the node image,"
  echo "#    never pulled. The node image digest pins them."
  prev=
  while IFS='|' read -r src ref; do
    [[ $src != "$prev" ]] && { echo; echo "# $src"; prev=$src; }
    qualify "$ref"
  done < <(sort <<<"$entries")
} >"$OUT"
echo "wrote $OUT ($(grep -c '@sha256:' "$OUT") images)"
